/**
 * Builds everything that is generated from the source:
 *
 *   gmail/Core.gs                      the shared rules in docs/app/core, bundled for Apps Script
 *   gmail/appsscript.json              the Standard project's manifest
 *   docs/*.html, docs/<page>/index.html  the website, from scripts/pages.mjs
 *   docs/app/index.html, outlook.html, auth.html, blank.html   the Microsoft 365 app pages
 *   docs/outlook/manifest.xml          the Outlook manifest without connection settings
 *   docs/version.json
 *   docs/sitemap.xml, docs/robots.txt, docs/site.webmanifest   for search engines, from
 *                                      scripts/seo.config.mjs (the head tags of each public page
 *                                      come from the same file, through scripts/pages.mjs)
 *   docs/download/<slug>-gmail.zip          Standard install for Gmail
 *   docs/download/<slug>-gmail-private.zip  Private install for Gmail (service and add-on)
 *   docs/download/<slug>-outlook.zip        Outlook manifest and guide
 *
 * Usage: npm run build   (Node 22 or later; no packages needed)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { NAME, SLUG, SITE_URL, ADDIN_ID, VERSION, PROVIDER, REPO_URL, RELEASE_DATE, DESCRIPTION } from "./site.config.mjs";
import { bundleCore } from "./lib/bundle.mjs";
import { zip } from "./lib/zip.mjs";
import { gmailManifest, GMAIL_FILES } from "./gmail-manifests.mjs";
import { gmailReadme, gmailPrivateReadme, outlookReadme } from "./guides.mjs";
import * as pages from "./pages.mjs";
import { outlookManifest } from "../docs/app/outlook/manifest.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const rel = (p) => path.relative(ROOT, p);
const at = (p) => path.join(ROOT, p);

/** The shared modules, in any order; the bundler sorts them by what they import. */
export const CORE_MODULES = ["text.js", "settings.js", "lists.js", "tickets.js", "mail.js"].map((f) => at("docs/app/core/" + f));

export function coreGs() {
  return bundleCore(CORE_MODULES, {
    globalName: "Core",
    banner: `/**
 * ${NAME} ${VERSION}: the rules shared by Gmail and Outlook (tickets, settings, assignment, due
 * times, and email wording). Generated by scripts/build.mjs from docs/app/core.
 * Do not edit this file by hand; change the modules and run npm run build.
 *
 * Copyright (c) 2026 ${PROVIDER}. MIT License; see LICENSE.
 */`,
  });
}

/** The license, put into every download package so each copy carries its terms. */
const licenseText = () => fs.readFileSync(at("LICENSE"), "utf8").replace(/\r\n?/g, "\n");

/** The files of one Apps Script project: { name: text }. kind: standard, addon, or service. */
export function gmailProject(kind, core = coreGs()) {
  const files = {};
  for (const name of GMAIL_FILES[kind]) files[name] = name === "Core.gs" ? core : fs.readFileSync(at("gmail/" + name), "utf8").replace(/\r\n?/g, "\n");
  files["appsscript.json"] = gmailManifest(kind);
  return files;
}

export const MANIFEST_INFO = { name: NAME, siteUrl: SITE_URL, addinId: ADDIN_ID, version: VERSION, provider: PROVIDER, description: DESCRIPTION };

/** Fixed timestamps (the release date), so a package only changes when its files do. */
function releaseDate() {
  const d = new Date(`${RELEASE_DATE}T12:00:00`);
  return Number.isNaN(d.getTime()) ? new Date(2026, 0, 1, 12) : d;
}

const entries = (files, prefix = "") => Object.keys(files).sort().map((name) => ({ name: prefix + name, data: files[name] }));

export function gmailPackage() {
  return zip([...entries(gmailProject("standard")), { name: "LICENSE.txt", data: licenseText() }, { name: "README.txt", data: gmailReadme() }], { date: releaseDate() });
}

export function gmailPrivatePackage() {
  return zip([...entries(gmailProject("service"), "service/"), ...entries(gmailProject("addon"), "addon/"), { name: "LICENSE.txt", data: licenseText() }, { name: "README.txt", data: gmailPrivateReadme() }], { date: releaseDate() });
}

export function outlookPackage() {
  return zip([{ name: `${SLUG}-manifest.xml`, data: outlookManifest(MANIFEST_INFO, null) }, { name: "LICENSE.txt", data: licenseText() }, { name: "README.txt", data: outlookReadme() }], { date: releaseDate() });
}

/** Every generated file: { "path from the repository root": text or bytes }. */
export function outputs() {
  const core = coreGs();
  return {
    "gmail/Core.gs": core,
    "gmail/appsscript.json": gmailManifest("standard"),
    "docs/index.html": pages.homePage(),
    "docs/demo/index.html": pages.demoPage(),
    "docs/install/index.html": pages.installPage(),
    "docs/help/index.html": pages.helpPage(),
    "docs/privacy/index.html": pages.privacyPage(),
    "docs/terms/index.html": pages.termsPage(),
    "docs/404.html": pages.notFoundPage(),
    "docs/app/index.html": pages.webAppPage(),
    "docs/app/outlook.html": pages.outlookPage(),
    "docs/app/auth.html": pages.authPage(),
    "docs/app/blank.html": pages.blankPage(),
    "docs/outlook/manifest.xml": outlookManifest(MANIFEST_INFO, null),
    "docs/sitemap.xml": pages.sitemapXml(),
    "docs/robots.txt": pages.robotsTxt(),
    "docs/site.webmanifest": pages.webManifest(),
    "docs/version.json": JSON.stringify({ name: NAME, version: VERSION, released: RELEASE_DATE, site: SITE_URL, repository: REPO_URL }, null, 2) + "\n",
    [`docs/download/${SLUG}-gmail.zip`]: gmailPackage(),
    [`docs/download/${SLUG}-gmail-private.zip`]: gmailPrivatePackage(),
    [`docs/download/${SLUG}-outlook.zip`]: outlookPackage(),
  };
}

function main() {
  console.log(`Building ${NAME} ${VERSION} for ${SITE_URL}`);
  // Core.gs first, because the packages read the other gmail files from disk beside it.
  const all = outputs();
  for (const file of Object.keys(all)) {
    const target = at(file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, all[file]);
    console.log("  wrote " + rel(target));
  }
  console.log("Done.");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (e) {
    console.error(e);
    process.exit(1);
  }
}
